def deep_merge(dst, src):
    """Ajoute recursivement les cles de src absentes de dst. Retourne (dst, n_added)."""
    added = 0
    for key, val in src.items():
        if isinstance(val, dict):
            node = dst.get(key)
            if not isinstance(node, dict):
                node = {}
                dst[key] = node
                # nouveau sous-arbre : compte ses feuilles
            node2, n = deep_merge(node, val)
            dst[key] = node2
            added += n
        else:
            if key not in dst:
                dst[key] = val
                added += 1
    return dst, added


def main():
    total = 0
    for lang in ("fr", "en", "de", "it", "es"):
        path = os.path.join(I18N_DIR, f"{lang}.i18n.json")
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        _, a1 = deep_merge(data, DATA[lang])
        _, a2 = deep_merge(data, EXTEND[lang])
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"{lang}: +{a1 + a2} cles")
        total += a1 + a2
    print(f"TOTAL: +{total} cles injectees")


if __name__ == "__main__":
    main()
